#  | What to calculate | Formula                                  |
# | ----------------- | ---------------------------------------- |
# | Discount          | `(price * discount_percent) / 100`       |
# | Discounted price  | `price - discount`                       |
# | Tax               | `(discounted_price * tax_percent) / 100` |
# | Final amount      | `discounted_price + tax`                 |



price = float(input("Enter purchase price: "))

if price >= 5000:
    discount_percent = 20
elif price >= 2000:
    discount_percent = 10
else:
    discount_percent = 0

discount = price * discount_percent / 100
discounted_price = price - discount

tax = discounted_price * 18 / 100
final_amount = discounted_price + tax

print("Original Price:", price)
print("Discount Percentage:", discount_percent, "%")
print("Discount Amount:", discount)
print("Discounted Price:", discounted_price)
print("Tax (18%):", tax)
print("Final Amount:", final_amount)



